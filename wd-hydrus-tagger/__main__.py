_CHECKPOINT_FILE = "checkpoint.txt"

def write_checkpoint(file_hash: str) -> None:
    """Write the hash currently being processed to the checkpoint file.

    Called *before* fetching/processing so that if the process crashes mid-file
    the next run can detect the incomplete attempt.

    :param file_hash: Hash about to be processed.
    """
    try:
        with open(_CHECKPOINT_FILE, "w", encoding="utf-8") as f:
            f.write(file_hash + "\n")
    except OSError:
        pass

def clear_checkpoint() -> None:
    """Remove the checkpoint file after a file is successfully committed."""
    try:
        os.remove(_CHECKPOINT_FILE)
    except OSError:
        pass

def check_stale_checkpoint() -> Optional[str]:
    """Return the hash from a leftover checkpoint file, or None.

    A leftover file means the previous run crashed mid-file.  The caller
    decides whether to skip or retry that hash.

    :returns: The stale hash string, or ``None`` if no checkpoint exists.
    """
    if os.path.exists(_CHECKPOINT_FILE):
        try:
            with open(_CHECKPOINT_FILE, "r", encoding="utf-8") as f:
                h = f.read().strip()
            return h if h else None
        except OSError:
            return None
    return None


# -----------------------------
# Graceful Hydrus reconnect
# -----------------------------
def hydrus_call_with_reconnect(fn, *args, reconnect_retries: int = 5, reconnect_delay: int = 30, label: str = "Hydrus call", **kwargs) -> Any:
    """Call any Hydrus API function, retrying on connection failures with a countdown."""
    for attempt in range(reconnect_retries):
        try:
            return fn(*args, **kwargs)
        except (RuntimeError, OSError, ConnectionError) as e:
            if attempt >= reconnect_retries - 1:
                raise
            for remaining in range(reconnect_delay, 0, -1):
                sys.stdout.write(
                    f"\r[!] Hydrus unreachable ({label}) — retrying in {remaining:2d}s "
                    f"(attempt {attempt + 1}/{reconnect_retries})  "
                )
                sys.stdout.flush()
                time.sleep(1)
            sys.stdout.write("\r" + " " * 80 + "\r")
            sys.stdout.flush()
            logging.warning(f"Hydrus reconnect attempt {attempt + 1}/{reconnect_retries} ({label}): {e}")
    raise RuntimeError("Hydrus reconnect exhausted")


def get_file_with_retry(client: hydrus_api.Client, file_hash: str, retries: int = 5, delay: int = 5) -> Any:
    """Fetch a file from a Hydrus server with retry semantics.

    The function wraps ``client.get_file`` and will retry transient API
    failures up to ``retries`` times, sleeping ``delay`` seconds between
    attempts. If Hydrus reports a missing file (``FileMissingException``) the
    exception is propagated immediately.

    :param client: Hydrus API client used to fetch files.
    :param file_hash: Hydrus file hash to request.
    :param retries: Number of attempts before giving up.
    :param delay: Seconds to sleep between retry attempts.
    :returns: The response object returned by ``client.get_file``.
    :raises APIError: When Hydrus reports an unrecoverable API error.
    """
    for attempt in range(retries):
        try:
            return client.get_file(file_hash)
        except APIError as e:
            try:
                info = e.response.json()
            except Exception:
                info = {"status_code": getattr(getattr(e, 'response', None), 'status_code', None), "exception_type": None, "text": getattr(getattr(e, 'response', None), 'text', str(e))}

            if info.get("exception_type") == "FileMissingException":
                raise

            if attempt < retries - 1:
                logging.warning(f"retry {attempt} file: {file_hash}")
                time.sleep(delay)
                continue

            logging.error(f"retry fail file: {file_hash}")
            raise




