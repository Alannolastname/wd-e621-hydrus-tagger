"""Command-line entrypoint for the WD Hydrus Tagger utility.

This module provides a Click-based CLI that queries a Hydrus server for files
and applies tags generated by a local tagging model. It includes helpers to
request files with retry semantics and to run batch evaluations either from a
hash list or by searching Hydrus tags. It also exposes a video-processing
batch command which samples frames from GIFs/videos, aggregates per-frame
tags and writes the combined tags back to Hydrus.

The public commands exported to the Click CLI are:

- ``evaluate_api_batch``: process single-frame images (existing behavior)
- ``evaluate_api_batch_video``: process multi-frame content (GIF/video)

most functions in this module use type hints and Sphinx-style docstrings.
"""



