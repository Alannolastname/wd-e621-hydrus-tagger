def process_frames_streaming(
    frame_generator: Iterator[PILImage],
    interrogator,
    metadata_frames,
    file_hash: str,
    similarity_threshold: float,
    threshold: float,
    ratingsflag: bool,
    debug,
    controller: Optional["BatchController"] = None,
):
    """
    True streaming frame processor with live progress bar.
    No frame list is stored.

    If ``controller`` is provided, :py:meth:`BatchController.check_pause` is
    called after each frame so that a ``p`` keypress pauses mid-video.
    """

    agg_ratings: dict[str, float] = {}
    tag_stats = {}
    COLLECTION_THRESHOLD = threshold * 0.65
    last_small: Optional[PILImage] = None
    kept_count = 0
    total_count = 0

    # Mutable refs so BatchController.print_status can read live frame progress
    kept_ref  = [0]
    total_ref = [0]
    if controller is not None:
        controller.attach_frame_refs(kept_ref, total_ref, metadata_frames)
        click.echo(_LEGEND)

    try:
        for img in frame_generator:
            total_count += 1
            total_ref[0] = total_count

            pct        = int(total_count / metadata_frames * 100) if metadata_frames else 0
            bar_filled = int(pct / 2)
            bar_str    = "#" * bar_filled + "-" * (50 - bar_filled)
            sys.stdout.write(
                f"\r  [{bar_str}] {pct:3d}%  "
                f"Frame:{total_count}/{metadata_frames}  Tagged:{kept_count}\033[K"
            )
            sys.stdout.flush()

            # similarity check
            small = img.resize((64, 64)).convert("L")

            keep_frame = False
            if last_small is None:
                keep_frame = True
            else:
                diff = ImageChops.difference(small, last_small)
                stat = ImageStat.Stat(diff)
                mean_diff = sum(stat.mean) / len(stat.mean)
                if mean_diff >= similarity_threshold:
                    keep_frame = True

            if not keep_frame:
                small.close()
                img.close()
                if controller is not None:
                    if controller.check_pause(file_hash):
                        break   # skip requested mid-frame — exit generator loop
                continue

            # Frame is being kept/tagged
            kept_count += 1
            kept_ref[0] = kept_count

            if last_small is not None:
                last_small.close()
            last_small = small

            ratings, tags = interrogator.interrogate(img)

            for t, s in tags.items():
                score = float(s)
                if score > COLLECTION_THRESHOLD:
                    if t not in tag_stats:
                        tag_stats[t] = {"max": score, "sum": score, "count": 1}
                    else:
                        tag_stats[t]["max"] = max(tag_stats[t]["max"], score)
                        tag_stats[t]["sum"] += score
                        tag_stats[t]["count"] += 1

            if ratingsflag:
                for r, s in ratings.items():
                    score = float(s)
                    if score > COLLECTION_THRESHOLD:
                        agg_ratings[r] = max(agg_ratings.get(r, 0.0), score)

            img.close()

            if controller is not None:
                if controller.check_pause(file_hash):
                    break   # skip requested mid-frame — exit generator loop

        sys.stdout.write("\n")
        sys.stdout.flush()

    finally:
        if controller is not None:
            controller.detach_frame_refs()


    if last_small is not None:
        last_small.close()
        last_small = None

    if kept_count == 0:
        logging.warning(f"{file_hash}: Somehow all frames were filtered by similarity ?!?!!")
        return {}, {}, 0, total_count



    clipped_tags = {}
    rejected_tags = {}
    MIN_TAG_FREQUENCY = max(0.05, min(0.15, 1.0 / kept_count))

    # First pass — store all derived values, not just final_score
    all_tag_data = {}
    for tag, stats in tag_stats.items():
        max_score = stats["max"]
        avg_score = stats["sum"] / stats["count"]
        freq = stats["count"] / kept_count
        final_score = 0.4 * max_score + 0.3 * avg_score + 0.3 * (freq * max_score)
        all_tag_data[tag] = {
            "max_score": max_score,
            "avg_score": avg_score,
            "freq": freq,
            "final_score": final_score,
        }

    if debug:
        sorted_tags = sorted(all_tag_data.items(), key=lambda x: x[1]["final_score"], reverse=True)
        rank_by_tag = {tag: rank + 1 for rank, (tag, _) in enumerate(sorted_tags)}
    else:
        rank_by_tag = {}
        
    # Second pass — no recomputation needed
    for tag, stats in tag_stats.items():
        d = all_tag_data[tag]
        tag_record = {
            "max_score": d["max_score"],
            "avg_score": d["avg_score"],
            "sum_score": stats["sum"],
            "frame_count": stats["count"],
            "frequency": d["freq"],
            "final_score": d["final_score"],
            "threshold": threshold,
            "min_frequency": MIN_TAG_FREQUENCY,
            "kept_frames": kept_count,
        }

        reasons = []

        if d["freq"] < MIN_TAG_FREQUENCY:
            reasons.append("low_frequency")
        if d["final_score"] <= threshold:
            reasons.append("low_final_score")

        if reasons:
            tag_record["reasons"] = reasons
            if debug:
                tag_record["rank_if_sorted_by_score"] = rank_by_tag[tag]
            rejected_tags[tag] = tag_record
        else:
            clipped_tags[tag] = d["final_score"]


    rejected_tags = dict(
        sorted(rejected_tags.items(), key=lambda x: x[1]["final_score"], reverse=True)
    )

    clipped_tags = dict(
    sorted(clipped_tags.items(), key=lambda x: x[1], reverse=True)
    )   

    if debug:
        test_file = Path("test.txt")
        with test_file.open("w") as f:
            f.write(f"agg_ratings :\n{agg_ratings}\n\n")
            f.write(f"clipped_tags: \n{clipped_tags}\n\n")
            f.write(f"rejected_tags:\n{rejected_tags}\n\n")
        click.echo(agg_ratings)
        click.echo()
        click.echo(clipped_tags)
        click.echo("Debug mode: press Enter to exit.")
        input()

    tag_stats.clear()
    all_tag_data.clear()
    if not debug:
        rejected_tags.clear()


    agg_scores = clipped_tags
    return agg_scores, agg_ratings, kept_count, total_count


def dynamic_threshold(metadata_frames: float, metadata_video_duration: float, metadata_width: int, metadata_height: int) -> float:
    
    # Partial fallbacks — use what we have
    if not metadata_frames and not metadata_video_duration:
        # Truly no info at all — conservative middle ground
        return 6.0

    # Resolution factor — works even without frame/duration data
    original_max_dim = max(metadata_width, metadata_height) if (metadata_width and metadata_height) else 448
    scale_ratio = 448 / original_max_dim
    res_adjust = max(-2.0, 0.3 * math.log(1 / scale_ratio)) if scale_ratio > 0 else 0

    if metadata_frames and not metadata_video_duration:
        # Have frame count but no duration — can't compute fps, assume 24fps
        assumed_fps = 24.0
        base = 0.5 * math.log(max(metadata_frames, 1)) + 1.0
        fps_adjust = 0.15 * math.log(max(assumed_fps, 1))
        return max(2.0, min(base + fps_adjust + res_adjust, 15.0))

    if metadata_video_duration and not metadata_frames:
        # Have duration but no frame count — estimate frames at 24fps
        duration_seconds = metadata_video_duration / 1000.0
        estimated_frames = duration_seconds * 24.0
        base = 0.5 * math.log(max(estimated_frames, 1)) + 1.0
        fps_adjust = 0.15 * math.log(24.0)
        return max(2.0, min(base + fps_adjust + res_adjust, 15.0))

    # Both available — full calculation
    duration_seconds = metadata_video_duration / 1000.0
    fps = metadata_frames / duration_seconds if duration_seconds > 0 else 24.0
    base = 0.5 * math.log(max(metadata_frames, 1)) + 1.0
    fps_adjust = 0.15 * math.log(max(fps, 1))
    return max(2.0, min(base + fps_adjust + res_adjust, 15.0))


def pil_frame_gen(data: bytes) -> Iterator[PILImage]:
    count = 0
    with Image.open(BytesIO(data)) as container:
        n = getattr(container, "n_frames", 1)
        for i in range(n):
            container.seek(i)
            count += 1
            yield container.copy().convert("RGB").resize((448, 448))
    logging.info(f"[pil] Total frames extracted: {count}")


def ffmpeg_frame_gen(data: bytes, h: str, tmp_dir: Path, ffmpeg_exe):
    count = 0
    in_path = tmp_dir / f"vid_{h}"
    in_path.write_bytes(data)

    del data
    gc.collect()


    out_pattern = str(tmp_dir / f"frame_{h}_%05d.jpg")
    
    subprocess.run([ffmpeg_exe, "-y", "-i", str(in_path), 
                    "-vf", "scale=448:448:flags=bicubic", 
                    "-pix_fmt", "rgb24",
                    "-fps_mode", "passthrough", 
                    "-q:v", "2",
                    out_pattern
                ], stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL, check=False)
    
    frames = sorted(tmp_dir.glob(f"frame_{h}_*.jpg"))
    if not frames:
        logging.warning(f"[ffmpeg] No frames extracted for {h} — ffmpeg may have failed")
        if in_path.exists(): in_path.unlink()
        return

    try:
        for p in frames:
            with Image.open(p) as f_img:
                count += 1
                yield f_img.convert("RGB")
            p.unlink()
        logging.info(f"[ffmpeg] Total frames extracted: {count}")
    finally:
        # Clean up any frame files that weren't consumed (e.g. exception mid-loop)
        for p in frames:
            if p.exists():
                p.unlink()
        if in_path.exists():
            in_path.unlink()


@click.command()
@click.option("--hashfile", help="Text file containing Hydrus hashes")
@click.option("--search-tag", multiple=True,
              help="Hydrus tag(s) to search for (can be used multiple times)")
@click.option("--token", required=True, help="Hydrus API token")
@click.option("--cpu", default=True, help="False to Use GPU instead of CPU")
@click.option("--model", default="wd-eva02-large-tagger-v3",
              help="Tagging model to use")
@click.option("--threshold", default=0.35,
              help="Threshold to drop tags below")
@click.option("--host", default="http://127.0.0.1:45869",
              help="The URL for your Hydrus server ")
@click.option("--tag-service", default="ai tags",
              help="The Hydrus tag service to add tags to")
@click.option("--ratings-only", default=False,
              help="Strip all tags except content rating")
@click.option("--privacy", default=True,
              help="Hide tag output from cli")
@click.option("--debug", is_flag=True, default=False,
              help="Show debug progress for video processing")
@click.option("--max-files", default=0,
              help="Stop after processing this many files (0 = no limit)")
def evaluate_api_batch_video(hashfile: Optional[str], search_tag: tuple[str, ...], token: str, cpu: bool,
                             model: str, threshold: float, host: str,
                             tag_service: str, ratings_only: bool, privacy: bool, debug: bool,
                             max_files: int) -> None:
    """Evaluate a batch of multi-frame content (GIF/video) and apply tags with RAM optimization.

    This command is similar to :func:`evaluate_api_batch` but targets
    multi-frame content. For animated GIFs the frames are read via PIL; for
    other video containers the function will attempt to use ``ffmpeg`` (if
    available) to extract one frame per second. Frames are dynamically
    filtered for similarity before interrogation for efficiency.

    The per-frame tag scores are aggregated (averaged) and the resulting tag
    list is applied to the original video file in Hydrus.

    :param hashfile: Optional path to a newline-separated file containing
        Hydrus file hashes to process.
    :param search_tag: One or more Hydrus tags to search for; mutually
        exclusive with ``hashfile``.
    :param token: Hydrus API token for authentication.
    :param cpu: When True, run the interrogator in CPU mode; False to prefer GPU.
    :param model: Local model folder name to load (under ``./model``).
    :param threshold: Minimum tag score threshold to include a tag.
    :param host: URL of the target Hydrus server.
    :param tag_service: Name of the Hydrus tag service to which tags are added.
    :param ratings_only: If True, only the content rating tag is added.
    :param privacy: If True, suppress tag output to the CLI.
    """

    repo_root = Path(__file__).resolve().parents[1]
    repo_tmp_dir = repo_root / "ffmpeg_temp"
    repo_tmp_dir.mkdir(parents=True, exist_ok=True)

    bundled_ffmpeg = repo_root / "ffmpeg" / "bin" / ("ffmpeg.exe" if os.name == "nt" else "ffmpeg")
    ffmpeg_exe = str(bundled_ffmpeg) if bundled_ffmpeg.exists() else "ffmpeg"

    # Setup logging and model like the image batch command
    os.makedirs("logs", exist_ok=True)
    timestamp = datetime.now().strftime("%Y-%m-%d_%H-%M-%S")
    logfile = f"logs/{model}_{timestamp}.log"

    logging.basicConfig(
        filename=logfile,
        level=logging.INFO,
        format="%(asctime)s - %(message)s"
    )

    logging.info("=== WD HYDRUS VIDEO TAGGER START ===")
    logging.info(f"Model: {model}")
    logging.info(f"CPU Mode: {cpu}")
    logging.info(f"Tag Service: {tag_service}")
        

    if not os.path.isfile('./model/' + model + '/info.json'):
        raise ValueError("info.json not found in model folder!")

    with open('./model/' + model + '/info.json') as json_f:
        modelinfo: dict[str, Any] = json.load(json_f)
        done_hashes_file: str = f"done-hashes-{modelinfo['modelname']}.txt"

    if ratings_only and not modelinfo['ratingsflag']:
        raise ValueError("--ratings-only set, but model does not support ratings!")

    interrogator: interrogate.WaifuDiffusionInterrogator = interrogate.WaifuDiffusionInterrogator(
        modelinfo['modelname'], # the name of the model for display purposes
        modelinfo['modelfile'], # the filename of the model file
        modelinfo['tagsfile'], # the filename of the tags file
        model, # the folder storing the previous two files as well as the info file
		modelinfo['ratingsflag'], # flag indicating whether model identifies content rating
		modelinfo['numberofratings'], # amount of tags to consider for content rating if so
        repo_id=modelinfo['source'], # source of the model, credit where credit is due
    )
    interrogator.load(cpu)

    client: hydrus_api.Client = hydrus_api.Client(token, host)

    # Determine file source (search for video content)
    using_tag_search: bool = False

    if search_tag:
        using_tag_search = True
        logging.info(f"Search Tags: {search_tag}")
        # Include only animated/video types not images
        query_tags: list[str] = list(search_tag) + ["system:filetype is ugoira, video"]
        click.echo("[INFO] Connecting to Hydrus and searching for files...")
        hashes: list[str] = cast(list[str], hydrus_call_with_reconnect(
            client.search_files,
            tags=query_tags, return_hashes=True, file_sort_asc=True, file_sort_type=16,
            label="search_files",
        ))

        click.echo(f"Found {len(hashes)} files (animated/video).")
        logging.info(f"Found {len(hashes)} files via tag search")

    elif hashfile:
        if not os.path.isfile(hashfile):
            raise ValueError("hashfile not found!")
        with open(hashfile) as f:
            hashes: list[str] = [line.strip() for line in f if line.strip()]
        logging.info(f"Loaded {len(hashes)} hashes from file")
    else:
        raise ValueError("Provide either --search-tag or --hashfile")

    done_hashes: set[str] = set()
    bad_hashes: set[str] = set()

    if not using_tag_search:
        if os.path.exists(done_hashes_file):
            with open(done_hashes_file, "r", encoding="utf-8") as f:
                done_hashes = {line.strip() for line in f if line.strip()}

    if os.path.exists("bad-hashes.txt"):
        with open("bad-hashes.txt", "r", encoding="utf-8") as f:
            bad_hashes = {line.strip() for line in f if line.strip()}

    counterh = 0
    totalh = len(hashes)

    def _show_idh(item) -> str:
        return f"{counterh}/{totalh} Done"

    # -----------------------------
    # Stale checkpoint check
    # -----------------------------
    stale = check_stale_checkpoint()
    if stale:
        click.echo(f"[!] WARNING: checkpoint.txt found — previous run may have crashed mid-file ({stale}).")
        click.echo("    That hash will be retried this run. Delete checkpoint.txt to suppress this warning.")
        logging.warning(f"Stale checkpoint detected: {stale}")

    processed_count = 0
    interrupted = False

    count_ref = [0]
    controller = BatchController(total=totalh, processed_count_ref=count_ref)
    _draw_legend()  # first draw — reactively from here on

    last_status_count = 0
    current_hash = ""

    try:
        with click.progressbar(hashes, item_show_func=_show_idh) as bar:
            for file_hash in bar:
                counterh += 1

                file_hash = str(file_hash)

                if not file_hash or file_hash in bad_hashes:
                    continue

                if not using_tag_search and file_hash in done_hashes:
                    continue

                if max_files > 0 and processed_count >= max_files:
                    _erase_legend()
                    click.echo(f"\n[*] --max-files limit of {max_files} reached. Stopping.")
                    logging.info(f"max-files limit {max_files} reached.")
                    interrupted = True
                    break

                current_hash = file_hash
                controller.reset_quit_frame_notification()
                write_checkpoint(file_hash)

                # -----------------------------
                # File metadata
                # -----------------------------
                try:
                    metadata = hydrus_call_with_reconnect(
                        client.get_file_metadata,
                        hashes=[file_hash],
                        label="get_file_metadata",
                    )
                except hydrus_api.APIError as e:
                    logging.warning(f"Metadata fetch failed for {file_hash}: {e}")
                    click.echo(f"  Skipping {file_hash}: metadata fetch failed.")
                    clear_checkpoint()
                    continue
                metadata_frames = metadata[0].get('num_frames') or 0
                metadata_video_duration = metadata[0].get('duration') or 0
                metadata_width = metadata[0].get('width') or 0
                metadata_height = metadata[0].get('height') or 0

                similarity_threshold_ff = dynamic_threshold(metadata_frames, metadata_video_duration, metadata_width, metadata_height)

                if metadata_frames:
                    click.echo(f"\n  Processing {metadata_frames} frames for hash {file_hash}")
                    logging.info(f"Processing {metadata_frames} frames for hash {file_hash}")
                    click.echo(f"  Similarity threshold > {similarity_threshold_ff:.2f}")
                    logging.info(f"Similarity threshold > {similarity_threshold_ff:.2f}")
                else:
                    click.echo(f"\n  Warning: {file_hash} has no frame metadata. Processing with fallback threshold {similarity_threshold_ff:.2f}.")
                    logging.warning(f"{file_hash}: no frame metadata, using fallback threshold {similarity_threshold_ff:.2f}")

                # --- Skip check (before expensive fetch) ---
                if controller.is_skip_requested():
                    controller.clear_skip()
                    clear_checkpoint()
                    _erase_legend()
                    click.echo(f"[>] Skipped: {file_hash}")
                    logging.info(f"Skipped by user: {file_hash}")
                    _redraw_legend()
                    continue

                try:
                    click.echo(f"  [INFO] Fetching video from Hydrus")
                    response: Any = hydrus_call_with_reconnect(
                        get_file_with_retry, client, file_hash, label="get_file",
                    )

                except hydrus_api.APIError as e:
                    info = e.response.json()
                    status = info.get("status_code")
                    etype = info.get("exception_type")
                    click.echo(f"Hydrus error {status} ({etype}) on {file_hash}")
                    logging.warning(f"Hydrus error {status} ({etype}) on {file_hash}")

                    if etype == "FileMissingException":
                        click.echo(f"Added to bad-hashes.txt: {file_hash}")
                        bad_hashes.add(file_hash)
                        with open("bad-hashes.txt", "a", encoding="utf-8") as bad_f:
                            bad_f.write(file_hash + "\n")
                        clear_checkpoint()
                        continue
                    else:
                        raise
                except RuntimeError as e:
                    click.echo(str(e))
                    click.echo("Hydrus seems unreachable — stopping batch.")
                    logging.error(str(e))
                    logging.error("Hydrus seems unreachable — stopping batch.")
                    raise

                click.echo("  [INFO] Preparation complete.")

                content = response.content
                try:
                    test_img = Image.open(BytesIO(content))
                    n_frames = getattr(test_img, "n_frames", 1)
                    test_img.close()
                    if n_frames > 1:
                        frame_gen = pil_frame_gen(content)
                        del content
                    else:
                        frame_gen = ffmpeg_frame_gen(content, file_hash, repo_tmp_dir, ffmpeg_exe)
                        del content
                except UnidentifiedImageError:
                    frame_gen = ffmpeg_frame_gen(content, file_hash, repo_tmp_dir, ffmpeg_exe)
                    del content

                agg_scores, agg_ratings, kept_frames, total_frames = process_frames_streaming(
                    frame_generator=frame_gen,
                    interrogator=interrogator,
                    metadata_frames=metadata_frames,
                    file_hash=file_hash,
                    similarity_threshold=similarity_threshold_ff,
                    threshold=threshold,
                    ratingsflag=modelinfo['ratingsflag'],
                    debug=debug,
                    controller=controller,
                )

                click.echo(f"tagged {kept_frames} of {total_frames} frames")
                logging.info(f"tagged {kept_frames} of {total_frames} frames")
                click.echo()

                # --- Skip check (after frame processing, before tag write) ---
                if controller.is_skip_requested():
                    controller.clear_skip()
                    clear_checkpoint()
                    _erase_legend()
                    click.echo(f"[>] Skipped (post-frames): {file_hash}")
                    logging.info(f"Skipped by user post-frames: {file_hash}")
                    _redraw_legend()
                    continue

                if kept_frames == 0:
                    logging.warning(f"Skipping tag write for {file_hash}: no frames were tagged.")
                    click.echo(f"  [WARN] Skipping: no frames tagged for {file_hash}.")
                    clear_checkpoint()
                    continue

                rating = "none"
                if modelinfo['ratingsflag']:
                    agg_ratings.setdefault("none", 0.0)
                    for r, score in agg_ratings.items():
                        if score > threshold and _RATING_PRIORITY.get(r, 0) > _RATING_PRIORITY.get(rating, 0):
                            rating = r

                if not ratings_only:
                    clipped_tags = [k.replace("_", " ") if k not in kaomojis else k for k in agg_scores]
                else:
                    clipped_tags = []

                if not privacy:
                    click.echo("rating: " + rating)
                    click.echo("tags: " + ", ".join(clipped_tags))
                    click.echo()

                if modelinfo['ratingsflag']:
                    clipped_tags.append("rating:" + rating)

                if ratings_only:
                    clipped_tags.append("ratings only " + modelinfo['modelname'] + " ai generated tags")
                else:
                    clipped_tags.append(f"{modelinfo['modelname']} ai generated tags")

                hydrus_call_with_reconnect(
                    client.add_tags,
                    hashes=[file_hash],
                    service_names_to_tags={tag_service: clipped_tags},
                    label="add_tags",
                )

                processed_count += 1
                count_ref[0] = processed_count
                gc.collect()
                clear_checkpoint()

                if not using_tag_search:
                    done_hashes.add(file_hash)
                    with open(done_hashes_file, "a", encoding="utf-8") as done_f:
                        done_f.write(file_hash + "\n")

                time.sleep(0.1)

                if processed_count % 25 == 0:
                    time.sleep(3)
                    logging.info(f"Processed {processed_count} files")

                # --- Periodic auto-status every 25 files (video batches are smaller) ---
                if processed_count - last_status_count >= 25:
                    last_status_count = processed_count
                    controller.print_status(current_hash)

                # --- Pause / skip / status / soft-quit check ---
                if controller.check(processed_count, current_hash):
                    interrupted = True
                    break

    except KeyboardInterrupt:
        interrupted = True
        click.echo("\n[!] Interrupted by user (Ctrl+C)")
        logging.warning("=== INTERRUPTED BY USER (CTRL+C) ===")

    finally:
        logging.info("=== WD HYDRUS VIDEO TAGGER FINISHED ===")
        logging.info(f"Total processed: {processed_count}")

        if interrupted:
            logging.info("Run ended due to manual interruption.")
        else:
            logging.info("Run completed normally.")

        logging.shutdown()

        click.echo(f"\nFinished. Total processed: {processed_count}")

        if debug:
            try:
                click.echo("Debug mode: press Enter to exit.")
                input()
            except Exception:
                # If stdin is not available, ignore and continue exiting
                pass



